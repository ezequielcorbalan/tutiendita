import { describe, expect, it } from "vitest";
import { customDomainIn, withCustomDomain } from "../../../src/packages/core/domain/custom-domain";
import { bucketNameFor, withProfessionalPhotos } from "../../../src/packages/core/domain/photo-storage";
import type { GithubConnection } from "../../../src/packages/core/domain/update";
import type { GithubClient } from "../../../src/packages/core/ports/github";
import {
  enableProfessionalPhotos,
  type PhotoStorageDeps,
  photoStorageStatus,
  revertProfessionalPhotos,
} from "../../../src/packages/core/use-cases/photo-storage";
import {
  InMemoryAccessRepository,
  InMemoryCredentialRepository,
  InMemorySessionRepository,
} from "./doubles/access";
import { FixedClock, InMemoryImageStorage, InMemorySettingsRepository } from "./doubles/in-memory";

const WRANGLER = `{
  // Generated by scripts/generate-tiendita.mjs.
  "$schema": "node_modules/wrangler/config-schema.json",
  "name": "tiendita",
  "d1_databases": [{ "binding": "DB", "database_name": "tiendita-db", "migrations_dir": "migraciones" }]
}
`;

const on = (text: string) => {
  const r = withProfessionalPhotos(text, true);
  if (!r.ok) throw new Error("expected ok");
  return r.value;
};

describe("withProfessionalPhotos", () => {
  it("adds the managed r2_buckets block after the opening brace, named after the worker", () => {
    const text = on(WRANGLER);
    expect(text).toContain('"r2_buckets": [{ "binding": "IMAGENES", "bucket_name": "tiendita-imagenes" }],');
    expect(text.startsWith("{\n  // tutiendita: professional photos")).toBe(true);
    expect(text).not.toBe(WRANGLER);
    expect(bucketNameFor("tiendita")).toBe("tiendita-imagenes");
  });

  it("is idempotent, and false removes the block back to the original file", () => {
    const text = on(WRANGLER);
    expect(on(text)).toBe(text);
    expect(withProfessionalPhotos(text, false)).toEqual({ ok: true, value: WRANGLER });
    expect(withProfessionalPhotos(text.replace(/\n/g, "\r\n"), false)).toMatchObject({ ok: true });
  });

  it("refuses when the file has its own r2_buckets (a mention in a comment doesn't count)", () => {
    const own = WRANGLER.replace('"name"', '"r2_buckets": [],\n  "name"');
    expect(withProfessionalPhotos(own, true)).toMatchObject({ ok: false, error: { code: "R2_ALREADY_SET" } });
    expect(withProfessionalPhotos(WRANGLER.replace("Generated", '"r2_buckets" are'), true).ok).toBe(true);
  });

  it("refuses without a worker name", () => {
    expect(withProfessionalPhotos(WRANGLER.replace('"name": "tiendita",', ""), true)).toMatchObject({
      ok: false,
      error: { code: "R2_ALREADY_SET", message: 'wrangler.jsonc has no "name"' },
    });
  });

  it("coexists with the custom domain block", () => {
    const withDomain = withCustomDomain(on(WRANGLER), "tienda.ejemplo.com");
    if (!withDomain.ok) throw new Error("expected ok");
    expect(customDomainIn(withDomain.value)).toBe("tienda.ejemplo.com");
    expect(withDomain.value).toContain("IMAGENES");
    const back = withProfessionalPhotos(withDomain.value, false);
    if (!back.ok) throw new Error("expected ok");
    expect(customDomainIn(back.value)).toBe("tienda.ejemplo.com");
    expect(back.value).not.toContain("IMAGENES");
  });
});

const START = new Date("2026-10-17T12:00:00.000Z");
const READY: GithubConnection = {
  appId: 7,
  slug: "tiendita-ana",
  privateKeyPem: "PEM",
  installationId: 99,
  repository: "ana/tiendita",
};
const PRIMARY = {
  origin: "https://tiendita.ana.workers.dev",
  rpId: "tiendita.ana.workers.dev",
  primary: true,
};

function build(o: { connection?: GithubConnection | null; hasBucket?: boolean; now?: Date } = {}) {
  const access = new InMemoryAccessRepository(
    new InMemoryCredentialRepository(),
    new InMemorySessionRepository(),
  );
  access.seedOwner(PRIMARY);
  const settings = new InMemorySettingsRepository();
  const images = new InMemoryImageStorage();
  let file = WRANGLER;
  const commits: { text: string; message: string }[] = [];
  const github = {
    readFile: async () => ({ text: file, sha: `sha-${commits.length}` }),
    writeFile: async (_c, f) => {
      commits.push({ text: f.text, message: f.message });
      file = f.text;
    },
  } as Partial<GithubClient> as GithubClient;
  const deps: PhotoStorageDeps = {
    settings,
    images,
    connection: {
      get: async () => (o.connection === undefined ? READY : o.connection),
      save: async () => {},
    },
    github,
    access,
    clock: new FixedClock(o.now ?? START),
    hasBucket: o.hasBucket ?? false,
  };
  return { deps, settings, images, commits, file: () => file };
}

describe("photo storage use cases", () => {
  it("status: basic by default, with usage, GitHub readiness and the bucket name", async () => {
    const { deps, images } = build({ connection: null });
    await images.save(new Uint8Array([1]), "image/png");
    expect(await photoStorageStatus(deps)()).toEqual({
      mode: "basic",
      used: 1,
      max: 200,
      github: false,
      bucketName: "tiendita-imagenes",
    });
    expect(await photoStorageStatus(build().deps)()).toMatchObject({ github: true });
  });

  it("enable without a GitHub connection fails", async () => {
    const { deps, commits } = build({ connection: null });
    expect(await enableProfessionalPhotos(deps)()).toMatchObject({
      ok: false,
      error: { code: "GITHUB_NOT_CONNECTED" },
    });
    expect(commits).toHaveLength(0);
  });

  it("enable writes the block, marks activating, and status fails after 5 minutes", async () => {
    const { deps, settings, commits, file } = build();
    expect(await enableProfessionalPhotos(deps)()).toEqual({
      ok: true,
      value: { bucketName: "tiendita-imagenes" },
    });
    expect(file()).toContain("IMAGENES");
    expect(commits[0]?.message).toBe("Activar fotos profesionales y sin límite");
    expect(await settings.get("fotos.modo")).toBe("activando");
    expect(await settings.get("fotos.pedido_en")).toBe(START.toISOString());
    expect(await photoStorageStatus(deps)()).toEqual({
      mode: "activating",
      since: START.toISOString(),
      failed: false,
      bucketName: "tiendita-imagenes",
    });
    const later = { ...deps, clock: new FixedClock(new Date(START.getTime() + 6 * 60 * 1000)) };
    expect(await photoStorageStatus(later)()).toMatchObject({ mode: "activating", failed: true });
  });

  it("revert from activating restores the file and the basic mode; elsewhere it is a no-op", async () => {
    const { deps, settings, commits, file } = build();
    expect(await revertProfessionalPhotos(deps)()).toEqual({ ok: true, value: undefined });
    expect(commits).toHaveLength(0);
    await enableProfessionalPhotos(deps)();
    expect(await revertProfessionalPhotos(deps)()).toEqual({ ok: true, value: undefined });
    expect(file()).toBe(WRANGLER);
    expect(commits[1]?.message).toBe("Volver a fotos básicas");
    expect(await settings.get("fotos.modo")).toBe("basica");
  });

  it("revert with the binding present leaves GitHub alone and keeps professional", async () => {
    const { deps, settings, commits } = build({ hasBucket: true });
    await settings.set("fotos.modo", "activando", START);
    expect(await revertProfessionalPhotos(deps)()).toEqual({ ok: true, value: undefined });
    expect(commits).toHaveLength(0);
    expect(await settings.get("fotos.modo")).toBe("profesional");
  });

  it("with the binding present it is professional, persisted once; enable doesn't touch GitHub", async () => {
    const { deps, settings, commits } = build({ hasBucket: true });
    await settings.set("fotos.modo", "activando", START);
    expect(await photoStorageStatus(deps)()).toEqual({ mode: "professional" });
    expect(await settings.get("fotos.modo")).toBe("profesional");
    expect(await enableProfessionalPhotos(deps)()).toMatchObject({ ok: true });
    expect(commits).toHaveLength(0);
  });
});
