import { describe, expect, it } from "vitest";
import { customDomainIn, normalizeHostname, withCustomDomain } from "../../../src/packages/core/domain/custom-domain";
import type { Store } from "../../../src/packages/core/domain/store";
import type { GithubConnection } from "../../../src/packages/core/domain/update";
import type { DomainDns } from "../../../src/packages/core/ports/domain-inspector";
import type { GithubClient } from "../../../src/packages/core/ports/github";
import {
  type CustomDomainDeps,
  checkDomain,
  connectDomain,
  disconnectDomain,
  domainStatus,
} from "../../../src/packages/core/use-cases/custom-domain";
import {
  InMemoryAccessRepository,
  InMemoryCredentialRepository,
  InMemorySessionRepository,
} from "./doubles/access";
import { FixedClock, InMemoryStoreRepository } from "./doubles/in-memory";

const WRANGLER = `{
  // Generated by scripts/generate-tiendita.mjs.
  "$schema": "node_modules/wrangler/config-schema.json",
  "name": "tiendita",
  "d1_databases": [{ "binding": "DB", "database_name": "tiendita-db", "migrations_dir": "migraciones" }]
}
`;

describe("normalizeHostname", () => {
  it("accepts what people paste and keeps the bare hostname", () => {
    expect(normalizeHostname(" https://Tienda.Ejemplo.com.ar/productos?x=1 ")).toEqual({
      ok: true,
      value: "tienda.ejemplo.com.ar",
    });
    expect(normalizeHostname("ejemplo.ar.")).toEqual({ ok: true, value: "ejemplo.ar" });
    expect(normalizeHostname("xn--tiend-ita.com")).toEqual({ ok: true, value: "xn--tiend-ita.com" });
  });

  it("rejects what can't be a domain of their own", () => {
    for (const bad of [
      "",
      "tienda",
      "tienda de ana.com",
      "-tienda.com",
      "a.b",
      "x.y.workers.dev",
      "x.pages.dev",
    ]) {
      expect(normalizeHostname(bad), bad).toMatchObject({ ok: false, error: { code: "INVALID_DOMAIN" } });
    }
  });
});

describe("withCustomDomain", () => {
  it("adds the managed block after the opening brace, keeping workers.dev on, and keeps everything else", () => {
    const r = withCustomDomain(WRANGLER, "tienda.ejemplo.com");
    if (!r.ok) throw new Error("expected ok");
    expect(r.value).toContain('"routes": [{ "pattern": "tienda.ejemplo.com", "custom_domain": true }],');
    expect(r.value).toContain('"workers_dev": true,');
    expect(r.value.replace(/\/\/.*$/gm, "")).toContain('"name": "tiendita"');
    expect(customDomainIn(r.value)).toBe("tienda.ejemplo.com");
    expect(r.value.startsWith("{\n  // tutiendita: custom domain")).toBe(true);
  });

  it("changing the domain replaces the block and null removes it, back to the original file", () => {
    const first = withCustomDomain(WRANGLER, "a.ejemplo.com");
    if (!first.ok) throw new Error("expected ok");
    const second = withCustomDomain(first.value, "b.ejemplo.com");
    if (!second.ok) throw new Error("expected ok");
    expect(customDomainIn(second.value)).toBe("b.ejemplo.com");
    expect(second.value.match(/"routes"/g)).toHaveLength(1);
    expect(withCustomDomain(second.value, null)).toEqual({ ok: true, value: WRANGLER });
    expect(withCustomDomain(second.value.replace(/\n/g, "\r\n"), null)).toMatchObject({ ok: true });
  });

  it("refuses when the file has routes of its own (a mention in a comment doesn't count)", () => {
    const own = WRANGLER.replace(
      '"name"',
      '"routes": [{ "pattern": "x.com/*", "zone_name": "x.com" }],\n  "name"',
    );
    expect(withCustomDomain(own, "tienda.ejemplo.com")).toMatchObject({
      ok: false,
      error: { code: "ROUTES_ALREADY_SET" },
    });
    expect(withCustomDomain(WRANGLER.replace("Generated", '"routes" are'), "a.ejemplo.com").ok).toBe(true);
  });
});

const CLOCK = new FixedClock(new Date("2026-10-16T12:00:00.000Z"));
const READY: GithubConnection = {
  appId: 7,
  slug: "tiendita-ana",
  privateKeyPem: "PEM",
  installationId: 99,
  repository: "ana/tiendita",
};
const PRIMARY = {
  origin: "https://tiendita.ana.workers.dev",
  rpId: "tiendita.ana.workers.dev",
  primary: true,
};
const STORE: Store = {
  id: "s1",
  name: "Tienda de Ana",
  description: "",
  logoKey: null,
  currency: "ARS",
  language: "es",
  contact: { whatsapp: null, email: null },
  domain: null,
  heartbeatEnabled: true,
  heartbeatSentAt: null,
};
const DELEGATED: DomainDns = {
  zone: "ejemplo.com",
  nameservers: ["ana.ns.cloudflare.com", "bob.ns.cloudflare.com"],
  records: [],
};

function build(
  o: { connection?: GithubConnection | null; dns?: DomainDns; serves?: boolean; file?: string | null } = {},
) {
  const access = new InMemoryAccessRepository(
    new InMemoryCredentialRepository(),
    new InMemorySessionRepository(),
  );
  access.seedOwner(PRIMARY);
  const store = new InMemoryStoreRepository();
  void store.save(STORE, CLOCK.now());
  let file = o.file === undefined ? WRANGLER : o.file;
  const commits: { text: string; sha: string; message: string }[] = [];
  const github = {
    readFile: async () => (file === null ? null : { text: file, sha: `sha-${commits.length}` }),
    writeFile: async (_c, f) => {
      commits.push({ text: f.text, sha: f.sha, message: f.message });
      file = f.text;
    },
  } as Partial<GithubClient> as GithubClient;
  const deps: CustomDomainDeps = {
    access,
    store,
    connection: {
      get: async () => (o.connection === undefined ? READY : o.connection),
      save: async () => {},
    },
    github,
    inspector: { dns: async () => o.dns ?? DELEGATED, servesStore: async () => o.serves ?? false },
    clock: CLOCK,
  };
  return { deps, access, store, commits };
}

describe("custom domain use cases", () => {
  it("check: delegated only when every nameserver is Cloudflare's; reports records already there", async () => {
    const { deps } = build({
      dns: { zone: "ejemplo.com", nameservers: ["ns1.nic.ar", "ana.ns.cloudflare.com"], records: ["A"] },
    });
    expect(await checkDomain(deps)("https://Tienda.Ejemplo.com")).toEqual({
      ok: true,
      value: {
        hostname: "tienda.ejemplo.com",
        zone: "ejemplo.com",
        delegated: false,
        nameservers: ["ns1.nic.ar", "ana.ns.cloudflare.com"],
        records: ["A"],
      },
    });
    expect((await checkDomain(build().deps)("tienda.ejemplo.com")).ok && true).toBe(true);
  });

  it("connect: commits the domain to wrangler.jsonc and allows its origin with the primary rpId", async () => {
    const { deps, access, commits } = build();
    expect(await connectDomain(deps)("tienda.ejemplo.com")).toEqual({
      ok: true,
      value: { hostname: "tienda.ejemplo.com" },
    });
    expect(commits).toHaveLength(1);
    expect(commits[0]?.sha).toBe("sha-0");
    expect(commits[0]?.message).toBe("Conectar la tienda al dominio tienda.ejemplo.com");
    expect(customDomainIn(commits[0]?.text ?? "")).toBe("tienda.ejemplo.com");
    expect(await access.allowedOrigins()).toEqual([
      PRIMARY,
      { origin: "https://tienda.ejemplo.com", rpId: "tiendita.ana.workers.dev", primary: false },
    ]);
    expect(await domainStatus(deps)()).toEqual({ status: "connecting", hostname: "tienda.ejemplo.com" });
  });

  it("connect refuses without GitHub, outside Cloudflare, on a name in use or on the store's own address", async () => {
    const code = async (b: ReturnType<typeof build>, host = "tienda.ejemplo.com") => {
      const r = await connectDomain(b.deps)(host);
      return r.ok ? "ok" : r.error.code;
    };
    expect(await code(build({ connection: null }))).toBe("GITHUB_NOT_CONNECTED");
    expect(await code(build({ dns: { ...DELEGATED, nameservers: ["ns1.nic.ar"] } }))).toBe(
      "DOMAIN_NOT_DELEGATED",
    );
    expect(await code(build({ dns: { ...DELEGATED, nameservers: [] } }))).toBe("DOMAIN_NOT_DELEGATED");
    expect(await code(build({ dns: { ...DELEGATED, records: ["CNAME"] } }))).toBe("DOMAIN_IN_USE");
    expect(await code(build(), "tiendita.ana.workers.dev")).toBe("INVALID_DOMAIN");
    expect(await code(build({ file: WRANGLER.replace('"name"', '"routes": [],\n  "name"') }))).toBe(
      "ROUTES_ALREADY_SET",
    );
    expect(await code(build({ file: null }))).toBe("ROUTES_ALREADY_SET");
  });

  it("status: github-needed or none without a domain; active (and saved) once it answers as the store", async () => {
    expect(await domainStatus(build({ connection: null }).deps)()).toEqual({ status: "github-needed" });
    expect(await domainStatus(build().deps)()).toEqual({ status: "none" });
    const b = build({ serves: true });
    await connectDomain(b.deps)("tienda.ejemplo.com");
    expect(await domainStatus(b.deps)()).toEqual({ status: "active", hostname: "tienda.ejemplo.com" });
    expect((await b.store.get())?.domain).toBe("tienda.ejemplo.com");
    // Reconnecting the same domain is allowed even though its DNS record exists now.
    b.deps = {
      ...b.deps,
      inspector: { ...b.deps.inspector, dns: async () => ({ ...DELEGATED, records: ["A"] }) },
    };
    expect((await connectDomain(b.deps)("tienda.ejemplo.com")).ok).toBe(true);
  });

  it("disconnect: removes the block, the origin and the saved domain", async () => {
    const b = build({ serves: true });
    await connectDomain(b.deps)("tienda.ejemplo.com");
    await domainStatus(b.deps)();
    expect(await disconnectDomain(b.deps)()).toEqual({ ok: true, value: { hostname: null } });
    expect(b.commits.at(-1)?.text).toBe(WRANGLER);
    expect(b.commits.at(-1)?.message).toBe("Desconectar el dominio propio");
    expect(await b.access.allowedOrigins()).toEqual([PRIMARY]);
    expect((await b.store.get())?.domain).toBeNull();
    expect(await domainStatus(b.deps)()).toEqual({ status: "none" });
  });
});
